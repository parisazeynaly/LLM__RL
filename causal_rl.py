def evaluate_rl_model_final(
    model_path,
    test_qs,
    test_refs,
    output_csv,
    max_steps=6,
    use_pag_guidance=False,
    pag_epsilon=0.1,
    deterministic=True,
):
    """
    Final evaluation function for your CausalRLBreakerEnv.

    Works for:
    1. Causal reward only:
       use_pag_guidance=False

    2. Causal reward + PAG-guided inference:
       use_pag_guidance=True
    """

    print("\n" + "=" * 70)
    print("FINAL EVALUATION STARTED")
    print("=" * 70)
    print(f"Model path        : {model_path}")
    print(f"Samples           : {len(test_qs)}")
    print(f"Max steps         : {max_steps}")
    print(f"PAG guidance      : {use_pag_guidance}")
    print(f"PAG epsilon       : {pag_epsilon}")
    print("=" * 70)

    model = PPO.load(model_path)

    env = CausalRLBreakerEnv(
        questions=test_qs,
        references=test_refs,
        max_steps=max_steps,
        train_mode=False,
        pag_epsilon=pag_epsilon,
        use_pag_guidance=use_pag_guidance,
    )

    all_results = []
    eval_start = time.time()

    for i, q in enumerate(test_qs):
        obs, _ = env.reset(options={"q_idx": i})

        done = False
        final_info = {}
        episode_logs = []
        steps = 0

        while not done:
            action, _ = model.predict(obs, deterministic=deterministic)
            obs, reward, terminated, truncated, info = env.step(int(action))

            episode_logs.append(info)
            final_info = info
            steps += 1

            done = terminated or truncated

        success = bool(final_info.get("success", False))

        total_tokens = sum(x.get("total_tokens", 0) for x in episode_logs)
        mutator_tokens = sum(x.get("mutator_tokens", 0) for x in episode_logs)
        target_tokens = sum(x.get("target_tokens", 0) for x in episode_logs)
        judge_tokens = sum(x.get("judge_tokens", 0) for x in episode_logs)

        total_latency = sum(x.get("latency_s", 0.0) for x in episode_logs)
        mutator_latency = sum(x.get("mutator_latency_s", 0.0) for x in episode_logs)
        target_latency = sum(x.get("target_latency_s", 0.0) for x in episode_logs)
        judge_latency = sum(x.get("judge_latency_s", 0.0) for x in episode_logs)

        judge_info = final_info.get("judge_info", {}) or {}

        all_results.append({
            "question_id": i,
            "success": success,
            "steps": steps,
            "qct": steps if success else 0,
            "ppo_action": final_info.get("ppo_action"),
            "executed_action": final_info.get("executed_action"),
            "pag_guided": final_info.get("pag_guided"),
            "reward": final_info.get("reward"),
            "total_tokens": total_tokens,
            "mutator_tokens": mutator_tokens,
            "target_tokens": target_tokens,
            "judge_tokens": judge_tokens,
            "latency_s": total_latency,
            "mutator_latency_s": mutator_latency,
            "target_latency_s": target_latency,
            "judge_latency_s": judge_latency,
            "judge_pattern": judge_info.get("pattern", "unknown"),
            "judge_confidence": judge_info.get("confidence_score", 0.0),
            "judge_relevance": judge_info.get("relevance_score", 0.0),
            "causal_vector": final_info.get("causal_vector"),
            "prompt": final_info.get("prompt"),
        })

        print(
            f"✅ Eval {i+1}/{len(test_qs)} | "
            f"success={success} | steps={steps}"
        )

    df = pd.DataFrame(all_results)

    os.makedirs(os.path.dirname(output_csv), exist_ok=True)
    df.to_csv(output_csv, index=False)

    eval_time = time.time() - eval_start

    success_df = df[df["success"] == True]
    fail_df = df[df["success"] == False]

    summary = {
        "N": len(df),
        "ASR_percent": float(df["success"].mean() * 100),
        "Success_count": int(df["success"].sum()),
        "Failure_count": int((~df["success"]).sum()),
        "Avg_steps_all": float(df["steps"].mean()),
        "Avg_QCT_success_only": float(success_df["qct"].mean()) if len(success_df) else 0.0,
        "Avg_tokens_all": float(df["total_tokens"].mean()),
        "Avg_tokens_success": float(success_df["total_tokens"].mean()) if len(success_df) else 0.0,
        "Avg_tokens_failure": float(fail_df["total_tokens"].mean()) if len(fail_df) else 0.0,
        "Avg_latency_all_s": float(df["latency_s"].mean()),
        "Avg_latency_success_s": float(success_df["latency_s"].mean()) if len(success_df) else 0.0,
        "Avg_latency_failure_s": float(fail_df["latency_s"].mean()) if len(fail_df) else 0.0,
        "Total_eval_time_minutes": eval_time / 60.0,
        "PAG_guidance": use_pag_guidance,
    }

    summary_df = pd.DataFrame([summary])
    summary_path = output_csv.replace(".csv", "_summary.csv")
    summary_df.to_csv(summary_path, index=False)

    print("\n" + "=" * 70)
    print("FINAL EVALUATION COMPLETE")
    print("=" * 70)
    print(f"Saved episodes : {output_csv}")
    print(f"Saved summary  : {summary_path}")
    print(f"ASR            : {summary['ASR_percent']:.2f}%")
    print(f"Success        : {summary['Success_count']} / {summary['N']}")
    print(f"Avg QCT        : {summary['Avg_QCT_success_only']:.2f}")
    print(f"Avg tokens     : {summary['Avg_tokens_all']:.0f}")
    print(f"Avg latency    : {summary['Avg_latency_all_s']:.2f}s")
    print(f"Eval time      : {summary['Total_eval_time_minutes']:.2f} min")
    print("=" * 70)

    return df, summary_df

