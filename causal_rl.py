def summarize(df, setting_name):
    rows = []
    for seed, g in df.groupby("seed"):
        rows.append({
            "setting": setting_name,
            "seed": seed,
            "N": len(g),
            "Success_Count": int(g["success"].sum()),
            "ASR_percent": float(g["success"].mean() * 100),
            "Avg_steps_all": float(g["steps"].mean()),
            "Avg_tokens_all": float(g["total_tokens"].mean()),
            "Avg_latency_all_s": float(g["latency_s"].mean()),
        })
    per_seed = pd.DataFrame(rows)
    agg = {
        "setting": setting_name,
        "N": df.shape[0] // len(SEEDS),
        "ASR_mean": per_seed["ASR_percent"].mean(),
        "ASR_std": per_seed["ASR_percent"].std(),
        "Tokens_mean": per_seed["Avg_tokens_all"].mean(),
        "Tokens_std": per_seed["Avg_tokens_all"].std(),
    }
    return per_seed, pd.DataFrame([agg])


