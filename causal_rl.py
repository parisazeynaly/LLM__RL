class EpsilonSchedule:
    def __init__(self, start=0.5, end=0.1, decay_steps=8000):
        self.start = start; self.end = end; self.decay_steps = decay_steps

    def get(self, step: int) -> float:
        return self.start + (self.end - self.start) * min(step / self.decay_steps, 1.0)

