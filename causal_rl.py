def get_groq_response(text: str, model_name: str, role: str = "target",
                      temperature: float = 0.7, max_tokens: int = 300,
                      max_retries: int = 8):
    """
    API wrapper — now uses Cerebras instead of Groq.
    Interface is identical so no other code needs to change.
    """
    if not text or not text.strip():
        return "", 0

    for attempt in range(max_retries):
        try:
            response = CEREBRAS_CLIENT.chat.completions.create(
                model=model_name,
                messages=[{"role": "user", "content": text}],
                temperature=temperature,
                max_tokens=max_tokens,
            )

            time.sleep(MODEL_SLEEP.get(model_name, 0.05))

            tokens = int(response.usage.total_tokens) if response.usage else 0
            PIPELINE_COUNTERS.increment_costs(role=role, calls=1, tokens=tokens)

            return response.choices[0].message.content or "", tokens

        except Exception as e:
            err = str(e).lower()
            wait = min((1.5 ** (attempt + 1)) + random.uniform(1, 3), 15.0)

            if "rate" in err or "429" in err or "quota" in err:
                print(f"⚠️ Rate limit on {model_name} "
                      f"(Attempt {attempt+1}/{max_retries}). "
                      f"Retrying in {wait:.2f}s...")
            else:
                print(f"⚠️ Connection error: {e} "
                      f"(Attempt {attempt+1}/{max_retries}). "
                      f"Retrying in {wait:.2f}s...")

            time.sleep(wait)

    return "", 0


