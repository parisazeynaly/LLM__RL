import numpy as np

class CausalActionMasker:
    def __init__(self, mutator_keys, config=None):
        self.mutator_keys = list(mutator_keys)
        self.num_actions = len(self.mutator_keys)

        # Define action tiers based on your causal graph structural pathways
        self.tier_1_direct = ["causal_framing", "causal_tone", "causal_combined"]
        self.tier_2_indirect = ["causal_complexity", "causal_obfuscation", "crossover", "generate"]
        self.tier_3_noise = ["rephrase", "shorten", "expand"]

        # Map keys to action indices for fast tensor masking
        self.t1_indices = [self.mutator_keys.index(m) for m in self.tier_1_direct if m in self.mutator_keys]
        self.t2_indices = [self.mutator_keys.index(m) for m in self.tier_2_indirect if m in self.mutator_keys]
        self.t3_indices = [self.mutator_keys.index(m) for m in self.tier_3_noise if m in self.mutator_keys]

    def compute_action_mask(self, current_obs, prev_obs=None, episode_step=0):
        """
        Generates a boolean mask array where True indicates the action is allowed.
        """
        # Initialize mask allowing all actions
        mask = np.ones(self.num_actions, dtype=bool)

        # Optimization 1: Hard prune Structural Noise if we need fast convergence
        # These do not change the causal graph properties
        if episode_step > 0:
            mask[self.t3_indices] = False

        # Optimization 2: Dynamic Stagnation Pruning
        if prev_obs is not None and episode_step >= 1:
            # Indices mapping: 1=obfuscation, 2=tone, 3=framing (based on your schema)
            prev_tone, prev_framing = float(prev_obs[2]), float(prev_obs[3])
            curr_tone, curr_framing = float(current_obs[2]), float(current_obs[3])

            # If direct causal paths are stalling or deteriorating, force Tier 1 intervention
            if curr_tone <= prev_tone and curr_framing <= prev_framing:
                # Completely block indirect actions to force prompt escalation
                mask[self.t2_indices] = False

        # Safeguard: If all actions get masked out by accident, default to Tier 1
        if not np.any(mask):
            mask[self.t1_indices] = True

        return mask

    def apply_mask_to_logits(self, action_logits, action_mask):
        """
        Applies the boolean mask to policy network outputs by setting
        forbidden actions to highly negative values (effectively 0 probability after Softmax).
        """
        masked_logits = np.copy(action_logits)
        masked_logits[~action_mask] = -1e9
        return masked_logits

